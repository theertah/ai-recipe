"""
prompt_engine.py — the "prompt engineering" piece of the project.

This module does no machine learning itself: it takes structured
inputs (a list of ingredients, a diet, a cuisine) and turns them into
a carefully designed prompt for a large language model, then parses
the model's response into a clean, structured recipe.

Set the LLM_PROVIDER environment variable to "openai", "anthropic", or "gemini"
depending on which API key you have (OPENAI_API_KEY / ANTHROPIC_API_KEY / GEMINI_API_KEY).
If none is set, a local offline fallback kicks in so the app still
works end-to-end for a demo without needing any API key.
"""

import os
import json

from dotenv import load_dotenv

load_dotenv()

PROVIDER = os.environ.get("LLM_PROVIDER", "mock")  # "openai" | "anthropic" | "gemini" | "mock"

# --- The actual prompt engineering happens here -----------------------
# A well-designed prompt for this task:
#   1. Gives the model a role ("professional home-cook chef").
#   2. Constrains the output format (strict JSON) so the frontend can
#      render it reliably without fragile text parsing.
#   3. Passes the user's real constraints (ingredients, diet, cuisine).
#   4. Asks for structured output only, no filler text.
PROMPT_TEMPLATE = """You are a professional home-cook chef and nutritionist.

A user has these ingredients available: {ingredients}.
Dietary preference: {diet}.
Preferred cuisine style: {cuisine}.

Create ONE realistic, easy-to-cook recipe using mostly these ingredients
(you may assume basic pantry staples like salt, oil, and water are
available).

Respond with STRICT JSON only, no extra text, no markdown fences,
using exactly this schema:

{{
  "title": string,
  "description": string (1-2 sentences),
  "prep_time_minutes": number,
  "cook_time_minutes": number,
  "servings": number,
  "ingredients": [string, ...],
  "steps": [string, ...],
  "nutrition_estimate": {{
    "calories": number,
    "protein_g": number,
    "carbs_g": number,
    "fat_g": number
  }}
}}
"""


def _build_prompt(ingredients, diet, cuisine):
    return PROMPT_TEMPLATE.format(
        ingredients=", ".join(ingredients),
        diet=diet,
        cuisine=cuisine,
    )


def _call_openai(prompt: str) -> str:
    from openai import OpenAI

    client = OpenAI()  # reads OPENAI_API_KEY from the environment
    response = client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[{"role": "user", "content": prompt}],
        temperature=0.7,
    )
    return response.choices[0].message.content


def _call_anthropic(prompt: str) -> str:
    import anthropic

    client = anthropic.Anthropic()  # reads ANTHROPIC_API_KEY from the environment
    response = client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=800,
        messages=[{"role": "user", "content": prompt}],
    )
    return response.content[0].text


def _call_gemini(prompt: str) -> str:
    import google.generativeai as genai

    # reads GEMINI_API_KEY from the environment automatically
    genai.configure(api_key=os.environ.get("GEMINI_API_KEY"))
    model = genai.GenerativeModel('models/gemini-flash-latest')
    
    # Generate the content
    response = model.generate_content(
        prompt,
        generation_config=genai.types.GenerationConfig(temperature=0.7)
    )
    return response.text


def _mock_recipe(ingredients, diet, cuisine):
    """
    Offline fallback so the project runs and can be demoed without an
    API key. Set LLM_PROVIDER to "openai" or "anthropic" for real
    LLM-generated recipes once you have a key.
    """
    main = ingredients[0] if ingredients else "your ingredients"
    return {
        "title": f"{main.title()} & Friends Skillet",
        "description": (
            f"A quick {cuisine if cuisine != 'any' else 'everyday'} skillet "
            f"built around {', '.join(ingredients)}."
        ),
        "prep_time_minutes": 10,
        "cook_time_minutes": 15,
        "servings": 2,
        "ingredients": ingredients + ["salt", "pepper", "olive oil"],
        "steps": [
            f"Wash and chop {', '.join(ingredients)} into bite-sized pieces.",
            "Heat a splash of olive oil in a pan over medium heat.",
            f"Add {ingredients[0] if ingredients else 'the ingredients'} first and cook for 3-4 minutes.",
            "Add the remaining ingredients and season with salt and pepper.",
            "Cook, stirring occasionally, for 8-10 minutes until everything is tender.",
            "Taste, adjust seasoning, and serve warm.",
        ],
        "nutrition_estimate": {
            "calories": 320,
            "protein_g": 12,
            "carbs_g": 30,
            "fat_g": 14,
        },
        "note": "Generated by the offline mock generator (no LLM API key set).",
    }


def generate_recipe(ingredients, diet="none", cuisine="any"):
    """
    Main entry point used by app.py. Returns a dict ready to be
    serialised to JSON for the frontend.
    """
    prompt = _build_prompt(ingredients, diet, cuisine)

    try:
        if PROVIDER == "openai":
            raw = _call_openai(prompt)
        elif PROVIDER == "anthropic":
            raw = _call_anthropic(prompt)
        elif PROVIDER == "gemini":
            raw = _call_gemini(prompt)
        else:
            return _mock_recipe(ingredients, diet, cuisine)

        raw = raw.strip()
        if raw.startswith("```"):
            raw = raw.strip("`")
            raw = raw[4:] if raw.lower().startswith("json") else raw
        return json.loads(raw)

    except Exception as exc:  # noqa: BLE001 - any failure should fall back gracefully
        fallback = _mock_recipe(ingredients, diet, cuisine)
        fallback["note"] = f"LLM call failed ({exc}); showing offline fallback recipe."
        return fallback
